    fireEvent.click(screen.getByRole('button', { name: '添加变量' }))
    fill('变量 1 名称', 'API_TOKEN')
    fill('变量 1 值', 'draft-token')
    fireEvent.click(screen.getByRole('button', { name: '保存配置' }))
